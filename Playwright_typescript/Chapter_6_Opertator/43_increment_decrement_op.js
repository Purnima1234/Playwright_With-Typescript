//increment and decrement operator
let x=10;
console.log(x) // 10    
x++; // post increment operator
console.log(x) // 11            
let y=20;
console.log(y) // 20
++y; // pre increment operator
console.log(y) // 21



let x=10;
let y=x++; // post increment operator
console.log(x) // 11
console.log(y) // 10    

//preincrement operator: - increase the value of x by 1 and then assign the value of x to y


let a=10;
let b=++a; // pre increment operator
console.log(a) // 11
console.log(b) // 11

//decrement operator: - decrease the value of x by 1 and then assign the value of x to y